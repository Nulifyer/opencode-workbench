import path from "node:path"
import { fileURLToPath } from "node:url"
import { PROTOCOL_V2_SCHEMA_SOURCE } from "../packages/shared/src/protocol-schema.ts"

const root = path.resolve(fileURLToPath(new URL("../", import.meta.url)))
const manifestPath = path.join(
  root,
  "packages",
  "shared",
  "generated",
  "protocol-v2-manifest.json",
)
const documentationPath = path.join(
  root,
  "docs",
  "reference",
  "protocol-v2.md",
)

function manifest(): string {
  return `${
    JSON.stringify(
      {
        schemaVersion: PROTOCOL_V2_SCHEMA_SOURCE.schemaVersion,
        protocol: PROTOCOL_V2_SCHEMA_SOURCE.protocol,
        errorCodes: PROTOCOL_V2_SCHEMA_SOURCE.errorCodes,
        capabilities: PROTOCOL_V2_SCHEMA_SOURCE.capabilities,
        limits: PROTOCOL_V2_SCHEMA_SOURCE.defaultLimits,
      },
      null,
      2,
    )
  }\n`
}

function documentation(): string {
  const envelopeRows = Object.entries(PROTOCOL_V2_SCHEMA_SOURCE.envelopes).map((
    [name, fields],
  ) => `| \`${name}\` | ${fields.map((field) => `\`${field}\``).join(", ")} |`)
    .join("\n")
  const capabilityRows = PROTOCOL_V2_SCHEMA_SOURCE.capabilities.map((name) =>
    `| \`${name}\` | Boolean; controls rendering and request admission |`
  ).join("\n")
  const errorRows = PROTOCOL_V2_SCHEMA_SOURCE.errorCodes.map((code) => `| \`${code}\` | Structured error code |`).join(
    "\n",
  )
  return `<!-- Generated by scripts/generate-protocol-artifacts.ts. Do not edit. -->
# Workbench protocol v2 reference

Protocol range: \`${PROTOCOL_V2_SCHEMA_SOURCE.protocol.minimum}-${PROTOCOL_V2_SCHEMA_SOURCE.protocol.maximum}\`

Compatibility decision: ${PROTOCOL_V2_SCHEMA_SOURCE.protocol.compatibilityDecision}

## Envelopes

| Envelope | Fields |
| --- | --- |
${envelopeRows}

## Capabilities

| Capability | Contract |
| --- | --- |
${capabilityRows}

## Structured errors

| Code | Contract |
| --- | --- |
${errorRows}

## Default limits

${
    Object.entries(PROTOCOL_V2_SCHEMA_SOURCE.defaultLimits).map((
      [name, value],
    ) => `- \`${name}\`: ${value}`).join("\n")
  }
`
}

async function check(pathname: string, expected: string): Promise<void> {
  const actual = await Deno.readTextFile(pathname).catch(() => undefined)
  if (actual !== expected) {
    throw new Error(
      `Generated protocol artifact is stale: ${path.relative(root, pathname)}. Run deno task generate:protocol.`,
    )
  }
}

const outputs = [[manifestPath, manifest()], [
  documentationPath,
  documentation(),
]] as const
if (Deno.args.includes("--check")) {
  for (const [pathname, content] of outputs) await check(pathname, content)
} else {
  for (const [pathname, content] of outputs) {
    await Deno.mkdir(path.dirname(pathname), { recursive: true })
    await Deno.writeTextFile(pathname, content)
  }
}
